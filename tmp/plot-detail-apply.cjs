// ═══════════ 2. systemPrompt 细化（surgical replace，每处必须恰好命中 1 次） ═══════════

function applyReplacements(agentId, text, reps) {
  for (const [from, to] of reps) {
    const count = text.split(from).length - 1;
    if (count !== 1) {
      throw new Error(`[${agentId}] 替换锚点命中 ${count} 次（预期 1）: ${JSON.stringify(from.slice(0, 60))}`);
    }
    text = text.replace(from, to);
  }
  return text;
}

